// Pre-draws the map outlines used by the Map study mode into public/maps/*.json, so the site
// needs no mapping library at runtime. Run with: node scripts/build-maps.mjs
// Data: us-atlas (US Census Bureau) and world-atlas (Natural Earth), both public domain / ISC.
import { readFileSync, writeFileSync } from "fs";
import { createRequire } from "module";
import { geoPath, geoEqualEarth, geoIdentity } from "d3-geo";
import { feature, mesh } from "topojson-client";

const require = createRequire(import.meta.url);
const round = (d) => d.replace(/-?\d+\.\d+/g, (n) => (+n).toFixed(1));

function build(file, object, projection, width, height, out, skip = []) {
  const topo = JSON.parse(readFileSync(require.resolve(file), "utf8"));
  const fc = feature(topo, topo.objects[object]);
  fc.features = fc.features.filter((f) => f.properties?.name && !skip.includes(f.properties.name));
  if (projection) projection.fitSize([width, height], fc);
  const path = geoPath(projection ?? geoIdentity());
  const shapes = fc.features.map((f) => ({ name: f.properties.name, d: round(path(f) || "") })).filter((s) => s.d);
  const borders = round(path(mesh(topo, topo.objects[object], (a, b) => a !== b)) || "");
  writeFileSync(`public/maps/${out}.json`, JSON.stringify({ viewBox: `0 0 ${width} ${height}`, shapes, borders }));
  return shapes.map((s) => s.name).sort();
}

const us = build("us-atlas/states-albers-10m.json", "states", null, 975, 610, "us-states");
const world = build("world-atlas/countries-110m.json", "countries", geoEqualEarth(), 960, 470, "world", ["Antarctica"]);
writeFileSync("src/lib/map-names.ts",
  "// Generated by scripts/build-maps.mjs: the exact place names each map knows.\n" +
  `export const MAP_NAMES = ${JSON.stringify({ "us-states": us, world }, null, 0)} as const;\n`);
console.log("us", us.length, "world", world.length);
